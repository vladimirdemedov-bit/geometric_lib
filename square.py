def area(a):
    ''' Принимает сторону a, возвращает площадь квадрата по формуле `S = a²`

        Параметры:
        - `a` : Сторона квадрата

        Возвращаемое значение:
        - `a**2` : Площадь квадрата'''
    return a * a


def perimeter(a):
    ''' Принимает сторону a, возвращает периметр квадрата по формуле `P = 4*a`

        Параметры:
        - `a` : Сторона квадрата

        Возвращаемое значение:
        - `4*a` : Периметр квадрата'''
    return 4 * a